
import os
import sqlite3
from pathlib import Path

import psycopg
from psycopg import sql
from dotenv import load_dotenv


# =====================================================
# CONFIGURATION
# =====================================================

BASE_DIR = Path(__file__).parent.parent
SQLITE_PATH = BASE_DIR / "database" / "career_finder.db"

ENV_PATH = Path(__file__).parent / ".env"
load_dotenv(ENV_PATH)

DATABASE_URL = os.getenv("DATABASE_URL")

TABLES = [
    "companies",
    "users",
    "applications",
    "cv",
    "favorites",
    "assistant_messages",
]

EXPECTED_COUNTS = {
    "companies": 217,
    "users": 6,
    "applications": 11,
    "cv": 6,
    "favorites": 1,
    "assistant_messages": 14,
}


# =====================================================
# POSTGRESQL TABLE STRUCTURE
# =====================================================

CREATE_TABLES = [

    """
    CREATE TABLE companies (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nom_entreprise TEXT NOT NULL,
        secteur TEXT,
        domaine TEXT,
        titre_poste TEXT,
        type_source TEXT,
        adresse TEXT,
        ville TEXT,
        note_entreprise DOUBLE PRECISION,
        nb_avis INTEGER,
        type_contrat TEXT,
        score_total DOUBLE PRECISION,
        priorite TEXT,
        statut_candidature TEXT,
        date_contact TEXT,
        notes_perso TEXT,
        lien TEXT,
        recherche_linkedin TEXT,
        email TEXT,
        site_web TEXT,
        telephone TEXT
    )
    """,

    """
    CREATE TABLE users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nom TEXT NOT NULL,
        email TEXT NOT NULL UNIQUE,
        mot_de_passe TEXT NOT NULL,
        date_creation TEXT DEFAULT (CURRENT_TIMESTAMP::text),
        avatar TEXT,
        prenom TEXT,
        nom_famille TEXT,
        telephone TEXT,
        date_naissance TEXT,
        email_verifie INTEGER DEFAULT 0,
        code_verif TEXT,
        code_expire TEXT,
        code_essais INTEGER DEFAULT 0
    )
    """,

    """
    CREATE TABLE applications (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL,
        company_id BIGINT NOT NULL,
        statut TEXT DEFAULT 'À préparer',
        date_candidature TEXT DEFAULT (CURRENT_TIMESTAMP::text),
        notes TEXT,
        cv_nom TEXT,
        FOREIGN KEY (user_id) REFERENCES users(id),
        FOREIGN KEY (company_id) REFERENCES companies(id)
    )
    """,

    """
    CREATE TABLE cv (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL,
        nom_fichier TEXT,
        texte_extrait TEXT,
        email_detecte TEXT,
        telephone_detecte TEXT,
        date_upload TEXT DEFAULT (CURRENT_TIMESTAMP::text),
        FOREIGN KEY (user_id) REFERENCES users(id)
    )
    """,

    """
    CREATE TABLE favorites (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL,
        company_id BIGINT NOT NULL,
        date_ajout TEXT DEFAULT (CURRENT_TIMESTAMP::text),
        UNIQUE (user_id, company_id)
    )
    """,

    """
    CREATE TABLE assistant_messages (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL,
        role TEXT NOT NULL,
        content TEXT NOT NULL,
        date_creation TEXT DEFAULT (CURRENT_TIMESTAMP::text),
        fichier_nom TEXT,
        fichier_path TEXT,
        fichier_mime TEXT
    )
    """,
]


# =====================================================
# MIGRATION
# =====================================================

def main():

    print("======================================")
    print(" MIGRATION SQLITE VERS NEON")
    print("======================================")

    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL introuvable dans backend/.env")

    if not SQLITE_PATH.exists():
        raise FileNotFoundError(
            f"Base SQLite introuvable : {SQLITE_PATH}"
        )

    # Connexion SQLite en lecture seulement
    sqlite_conn = sqlite3.connect(
        f"file:{SQLITE_PATH.as_posix()}?mode=ro",
        uri=True
    )

    try:
        with psycopg.connect(
            DATABASE_URL,
            connect_timeout=15
        ) as pg_conn:

            with pg_conn.cursor() as pg_cur:

                # Vérifier que Neon ne contient aucune table
                pg_cur.execute("""
                    SELECT table_name
                    FROM information_schema.tables
                    WHERE table_schema = 'public'
                      AND table_type = 'BASE TABLE'
                """)

                existing_tables = pg_cur.fetchall()

                if existing_tables:
                    raise RuntimeError(
                        "STOP : Neon contient déjà des tables. "
                        "Aucune modification effectuée."
                    )

                print("\n1. Création des 6 tables...")

                for statement in CREATE_TABLES:
                    pg_cur.execute(statement)

                print("Tables créées avec succès.")

                # Vérifier les nombres de lignes SQLite
                print("\n2. Vérification de SQLite...")

                for table in TABLES:
                    count = sqlite_conn.execute(
                        f'SELECT COUNT(*) FROM "{table}"'
                    ).fetchone()[0]

                    expected = EXPECTED_COUNTS[table]

                    if count != expected:
                        raise RuntimeError(
                            f"Nombre inattendu dans {table}: "
                            f"{count} au lieu de {expected}"
                        )

                    print(f"{table}: {count} lignes")

                # Transférer les données
                print("\n3. Transfert des données...")

                for table in TABLES:

                    source_cur = sqlite_conn.execute(
                        f'SELECT * FROM "{table}"'
                    )

                    columns = [
                        description[0]
                        for description in source_cur.description
                    ]

                    rows = source_cur.fetchall()

                    insert_query = sql.SQL(
                        "INSERT INTO {} ({}) VALUES ({})"
                    ).format(
                        sql.Identifier(table),
                        sql.SQL(", ").join(
                            sql.Identifier(column)
                            for column in columns
                        ),
                        sql.SQL(", ").join(
                            sql.Placeholder()
                            for _ in columns
                        )
                    )

                    if rows:
                        pg_cur.executemany(
                            insert_query,
                            rows
                        )

                    print(
                        f"{table}: {len(rows)} lignes transférées"
                    )

                # Synchroniser les séquences des identifiants
                print("\n4. Synchronisation des IDs...")

                for table in TABLES:
                    pg_cur.execute(
                        sql.SQL("""
                            SELECT setval(
                                pg_get_serial_sequence(%s, 'id'),
                                COALESCE(MAX(id), 1),
                                COUNT(*) > 0
                            )
                            FROM {}
                        """).format(sql.Identifier(table)),
                        (f"public.{table}",)
                    )

                # Vérification finale dans Neon
                print("\n5. Vérification des données dans Neon...")

                total = 0

                for table in TABLES:

                    pg_cur.execute(
                        sql.SQL(
                            "SELECT COUNT(*) FROM {}"
                        ).format(sql.Identifier(table))
                    )

                    neon_count = pg_cur.fetchone()[0]
                    expected = EXPECTED_COUNTS[table]

                    print(
                        f"{table}: {neon_count}/{expected}"
                    )

                    if neon_count != expected:
                        raise RuntimeError(
                            f"ERREUR : nombre incorrect dans {table}"
                        )

                    total += neon_count

                print("\n======================================")
                print(" MIGRATION TERMINEE AVEC SUCCES !")
                print("======================================")
                print(f"Total transféré : {total} lignes")

        # La transaction PostgreSQL est validée
        print("\nTransaction PostgreSQL validée.")

    finally:
        sqlite_conn.close()


if __name__ == "__main__":
    try:
        main()

    except Exception as error:
        print("\nERREUR DE MIGRATION :")
        print(error)
        print("La transaction PostgreSQL a été annulée si elle était ouverte.")
